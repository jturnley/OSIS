"""Assemble the MO2 mods of both editions from the xmake builds (`xmake build` makes both DLLs):
  mods/OStim Standalone Immersive Sex               the default release, compiled without the
                            non-consent features: build/lite/windows/x64/<mode>, plus dist/
  mods/OStim Standalone Immersive Sex (LoversLab)  the full plugin: build/windows/x64/<mode>, plus dist/
Each is OSIS.dll/.pdb plus the data folders (laid out like Data/). A folder listed first for an
edition would overlay dist/; none does now.

OSIS.ini and OSIS/morphs.json are not shipped: the plugin writes them on startup (and completes an
older INI), so installing an update over an old one cannot reset what the user chose.

The output folder is generated: each run deletes the files the previous run listed in
BUILD-OSIS.txt and writes a fresh set. Anything else in the folder (an archive you packed from it,
for example) is left alone. Archives are never copied in. This script never builds anything
itself; it warns when the DLL is older than its sources.

Finally it writes mods/<mod>.zip for each, installable in MO2 (the mod's files at the zip root,
so MO2 names the mod after the zip and finds its data directly).

Usage: python tools/assemble_mod.py [--patch]

With --patch it also writes mods/<mod> - <label> patch.zip for each: just the DLL and the README, to install over the
release before it (a hotfix). Without the PDB, so it is small; a crash log from it is read against the PDB kept in mods/<mod>/.
"""
import datetime
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# (mod folder, build folder, data folders: overlays first, dist last, README title suffix,
#  source files the edition's DLL is built without)
EDITIONS = [
    ('OStim Standalone Immersive Sex', os.path.join('build', 'lite', 'windows', 'x64'), ['dist'], '',
     {'voice.cpp', 'voice.h', 'scenelock.cpp', 'scenelock.h', 'spellcast.cpp', 'spellcast.h'}),
    ('OStim Standalone Immersive Sex (LoversLab)', os.path.join('build', 'windows', 'x64'), ['dist'], ' (LoversLab edition)', set()),
]
OUT = os.path.join(ROOT, 'mods', EDITIONS[0][0])  # the edition being assembled
MARKER = 'Generated by tools/assemble_mod.py'
DLL_NAME = 'OSIS'
BUILD_MODES = ['releasedbg', 'release', 'debug']  # preference order
ARCHIVES = ('.7z', '.zip', '.rar')  # packed copies of a mod folder, not mod content
MANIFEST_LINE = re.compile(r'^  (.+?) +\d+  .+$')

warnings = []
skipped = []


def newest(paths):
    return max((os.path.getmtime(p) for p in paths), default=0.0)


def files_under(d, content_only=False):
    for base, _dirs, names in os.walk(d):
        for n in names:
            p = os.path.join(base, n)
            if content_only and n.lower().endswith(ARCHIVES):
                skipped.append(os.path.relpath(p, ROOT))
                continue
            yield p


def place(src, dest, origin):
    """Copy src to dest; an existing identical file is fine, a different one is an error."""
    if os.path.exists(dest):
        with open(src, 'rb') as a, open(dest, 'rb') as b:
            same = a.read() == b.read()
        if not same:
            raise SystemExit('conflict: %s differs from the copy already placed at %s (from %s)'
                             % (src, os.path.relpath(dest, OUT), origin.get(dest)))
        return
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    shutil.copy2(src, dest)
    origin[dest] = os.path.relpath(src, ROOT)


def reset_output():
    """Delete what the previous run made (the files BUILD-OSIS.txt lists, plus BUILD-OSIS.txt and README-OSIS.md),
    then prune empty folders. Other files stay. The folder itself stays too: Windows can't remove
    a folder that is open in Explorer or is some process's working directory."""
    os.makedirs(OUT, exist_ok=True)
    build = os.path.join(OUT, 'BUILD-OSIS.txt')
    if not os.path.exists(build):
        if os.listdir(OUT):
            raise SystemExit('%s has files but no BUILD-OSIS.txt from this script; not touching it.' % OUT)
        return
    with open(build, encoding='utf-8') as f:
        lines = f.read().splitlines()
    if not lines or not lines[0].startswith(MARKER):
        raise SystemExit('%s/BUILD-OSIS.txt was not written by this script; not touching the folder.' % OUT)
    ours = ['BUILD-OSIS.txt', 'README-OSIS.md']
    in_files = False
    for line in lines:
        if line.startswith('Files (size, source):'):
            in_files = True
        elif in_files and MANIFEST_LINE.match(line):
            ours.append(MANIFEST_LINE.match(line).group(1))
    for rel in ours:
        p = os.path.join(OUT, rel)
        if os.path.isfile(p):
            os.remove(p)
    for base, dirs, files in os.walk(OUT, topdown=False):
        if base != OUT and not os.listdir(base):
            os.rmdir(base)


def foreign_files(origin):
    """Files in the output folder that this run did not write."""
    made = {os.path.normcase(p) for p in origin} | {os.path.normcase(os.path.join(OUT, n)) for n in ('BUILD-OSIS.txt', 'README-OSIS.md')}
    return sorted(os.path.relpath(p, OUT) for p in files_under(OUT) if os.path.normcase(p) not in made)


def find_dll(build_dir):
    for mode in BUILD_MODES:
        dll = os.path.join(ROOT, build_dir, mode, DLL_NAME + '.dll')
        if os.path.exists(dll):
            if mode != BUILD_MODES[0]:
                warnings.append('using the %s DLL build, not %s' % (mode, BUILD_MODES[0]))
            return dll
    raise SystemExit('no %s.dll under %s/{%s}; build it with xmake first'
                     % (DLL_NAME, build_dir.replace(os.sep, '/'), ','.join(BUILD_MODES)))


def project_version():
    """The version xmake.lua declares, as "1.2.3"."""
    with open(os.path.join(ROOT, 'xmake.lua'), encoding='utf-8') as f:
        m = re.search(r'set_version\("([0-9]+\.[0-9]+\.[0-9]+)"\)', f.read())
    return m.group(1) if m else None


def release_label():
    """The label src/Release.h declares ("beta 1"), or "" for a final release."""
    with open(os.path.join(ROOT, 'src', 'Release.h'), encoding='utf-8') as f:
        m = re.search(r'kLabel\s*=\s*"([^"]*)"', f.read())
    return m.group(1) if m else ''


def version_text():
    """"2.0.0 beta 1": the version xmake.lua declares, then the label."""
    label = release_label()
    return project_version() + (' ' + label if label else '')


def check_dll_version(dll):
    """The version resource is UTF-16 in the PE, so the declared version shows up as plain
    bytes. Missing means xmake reused a stale generated plugin-info file: the DLL would load,
    report the previous version, and make every later log and crash report misleading."""
    want = project_version()
    if not want:
        warnings.append('could not read set_version from xmake.lua; DLL version not checked')
        return
    with open(dll, 'rb') as f:
        blob = f.read()
    if ('%s.0' % want).encode('utf-16-le') in blob:
        return
    raise SystemExit(
        '%s does not carry version %s: xmake kept a stale plugin-info file.\n'
        '  Delete build/.gens/*/windows/x64/*/commonlibsse-ng-plugin.cpp and build again.'
        % (os.path.relpath(dll, ROOT), want))


def add_dll_route(origin, build_dir, data_dirs, without):
    dll = find_dll(build_dir)
    check_dll_version(dll)
    sources = [p for d in ('src', 'include') for p in files_under(os.path.join(ROOT, d))
               if os.path.basename(p).lower() not in without]
    if newest(sources) > os.path.getmtime(dll):
        warnings.append('%s is older than the newest file in src/ or include/: rebuild with xmake'
                        % os.path.relpath(dll, ROOT))
    plugins = os.path.join(OUT, 'SKSE', 'Plugins')
    place(dll, os.path.join(plugins, DLL_NAME + '.dll'), origin)
    pdb = os.path.splitext(dll)[0] + '.pdb'
    if os.path.exists(pdb):  # lets crash loggers name functions
        place(pdb, os.path.join(plugins, DLL_NAME + '.pdb'), origin)
    # Overlays come first; a later folder's file at a path already placed is the one it replaces.
    for data in data_dirs:
        base = os.path.join(ROOT, data)
        for p in files_under(base, content_only=True):
            dest = os.path.join(OUT, os.path.relpath(p, base))
            if dest in origin and data != data_dirs[0]:
                continue
            place(p, dest, origin)
    return dll


def write_zip(mod_dir):
    """mods/<mod>.zip with the mod's content at the root. Archives inside the folder are left out."""
    name = os.path.basename(mod_dir)
    dest = os.path.join(ROOT, 'mods', name + '.zip')
    tmp = dest + '.tmp'
    count = 0
    with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(files_under(mod_dir), key=str.lower):
            if p.lower().endswith(ARCHIVES):
                continue
            z.write(p, os.path.relpath(p, mod_dir).replace(os.sep, '/'))
            count += 1
    os.replace(tmp, dest)
    return dest, count


PATCH_FILES = ("SKSE/Plugins/OSIS.dll", "README-OSIS.md")  # not the PDB: it is 35 MB, nearly the whole of the full archive


def write_patch(mod_dir):
    """mods/<mod> - <label> patch.zip: the files a hotfix replaces, at the root like the full archive."""
    name = os.path.basename(mod_dir)
    dest = os.path.join(ROOT, 'mods', '%s - %s patch.zip' % (name, release_label() or project_version()))
    tmp = dest + '.tmp'
    with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for rel in PATCH_FILES:
            z.write(os.path.join(mod_dir, *rel.split('/')), rel)
    os.replace(tmp, dest)
    return dest


def git_head():
    try:
        head = subprocess.run(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD'],
                              capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(['git', '-C', ROOT, 'status', '--porcelain', '--', 'mods', 'tools'],
                               capture_output=True, text=True).stdout
        generated = ['mods/%s/' % name for name, *_ in EDITIONS]
        dirty = [l for l in dirty.splitlines()
                 if not any(g in l for g in generated) and not l.rstrip('"').lower().endswith(ARCHIVES)]
        return head + (' (+ uncommitted changes in mods/ or tools/)' if dirty else '')
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'


