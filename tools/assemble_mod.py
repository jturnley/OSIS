def main():
    global OUT
    for name, build_dir, data_dirs, edition, without in EDITIONS:
        OUT = os.path.join(ROOT, 'mods', name)
        warnings.clear()
        skipped.clear()
        assemble(build_dir, data_dirs, edition, without)
        if '--patch' in sys.argv[1:]:
            dest = write_patch(OUT)
            print('patch: %s, %d bytes' % (os.path.relpath(dest, ROOT), os.path.getsize(dest)))
    return 0


def assemble(build_dir, data_dirs, edition, without):
    reset_output()
    origin = {}
    dll = add_dll_route(origin, build_dir, data_dirs, without)
    with open(os.path.join(OUT, 'README-OSIS.md'), 'w', encoding='utf-8') as f:
        beta = ''
        known = ''
        if release_label():
            beta = ("\n> **This is a beta.** It is complete enough to use but has had limited testing. Back up your save, and send\n"
                    "> `Documents/My Games/Skyrim Special Edition/SKSE/OSIS.log` with any report. For a face problem, press\n"
                    "> \"Probe faces\" on the Face page first and play for a minute.\n")
            known = ("\n## Known issues in this beta\n\n"
                     "- A one-frame blink of eyes, brows and mood can show when a scene moves to a new animation node.\n"
                     "- PPA sometimes stops moving a penis for a few seconds and logs \"isn't managed by havok\" for the actor. Seen in testing; the cause is not known.\n"
                     "- Lip-sync reads uncompressed WAV moans only: voice packs in .fuz or xWMA, and packs of spoken lines, are not lip-synced.\n"
                     "- UBE: the blush textures are not shipped (convert Body Blushing's to the UBE UV) and the UBE slider values are a first estimate.\n"
                     "- The personalities, the own build-up faces and the shaped body response are new and have had little play-testing.\n")
        submissive = ''
        if edition:  # the personality is in the full edition only
            submissive = ("\n- **Submissive** (this edition only): turned on by rough scenes, and accepts any kind of scene, forced or not,"
                          " from someone with a relationship rank of 3 or 4 to everyone in it; it then plays as consensual.")
        f.write(README.replace('{edition}', edition).replace('{version}', version_text())
                .replace('{submissive_note}', submissive).replace('{submissive}', ', submissive' if edition else '')
                .replace('{beta}', beta).replace('{known}', known))  # edition is '' for the default download

    lines = [MARKER + ' on %s' % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
             'Project commit: %s' % git_head(),
             'DLL: %s (built %s)' % (os.path.relpath(dll, ROOT),
                                     datetime.datetime.fromtimestamp(os.path.getmtime(dll)).strftime('%Y-%m-%d %H:%M')),
             '']
    lines += ['WARNING: ' + w for w in warnings]
    kept = foreign_files(origin)
    lines += ['Kept (not made by this script): ' + k for k in kept]
    lines += ['Skipped archive: ' + s for s in skipped]
    lines += ['', 'Files (size, source):']
    for dest in sorted(origin, key=lambda d: os.path.relpath(d, OUT).lower()):
        lines.append('  %-72s %9d  %s' % (os.path.relpath(dest, OUT), os.path.getsize(dest), origin[dest]))
    with open(os.path.join(OUT, 'BUILD-OSIS.txt'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

    print('Wrote %s: %d files' % (os.path.relpath(OUT, ROOT), len(origin) + 2))
    for k in kept:
        print('kept (not ours): ' + k)
    for s in skipped:
        print('skipped archive: ' + s)
    dest, count = write_zip(OUT)
    print('zip: %s, %d files, %d bytes' % (os.path.relpath(dest, ROOT), count, os.path.getsize(dest)))
    for w in warnings:
        print('WARNING: ' + w)


if __name__ == '__main__':
    sys.exit(main())
