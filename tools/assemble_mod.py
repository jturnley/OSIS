"""Assemble the combined MO2 mod `mods/OSED Reborn` from both halves of the project.

Active (mod root):   the SKSE plugin route - OSEDReborn.dll/.pdb from the xmake build, plus
                     everything under dist/ (laid out like Data/).
Inert fallback:      the four fixed Papyrus mods, merged under `optional/Papyrus Fallback/`.
                     The game never loads anything from Data/optional/, so the two engines
                     can't both drive faces; README.md says how to swap.

The output folder is generated: each run deletes the files the previous run listed in
BUILD.txt and writes a fresh set. Anything else in the folder (an archive you packed from it,
for example) is left alone. Archives are never copied in. This script never builds anything
itself; it warns when the DLL or a .pex is older than its sources.

Finally it writes an MO2-installable zip for each of the five mods into mods/ (the mod's
files at the zip root, so MO2 names the mod after the zip and finds its data directly).

Usage: python tools/assemble_mod.py
"""
import datetime
import glob
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'mods', 'OSED Reborn')
FALLBACK = os.path.join(OUT, 'optional', 'Papyrus Fallback')
MARKER = 'Generated by tools/assemble_mod.py'
DLL_NAME = 'OSEDReborn'
BUILD_MODES = ['releasedbg', 'release', 'debug']  # preference order
PAPYRUS_MODS = ['OSED Reborn Core', 'OSED Reborn Body', 'OSED Reborn Living Skin', 'OSED Reborn Lip-Sync']
ARCHIVES = ('.7z', '.zip', '.rar')  # packed copies of a mod folder, not mod content
MANIFEST_LINE = re.compile(r'^  (.+?) +\d+  .+$')

warnings = []
skipped = []


def newest(paths):
    return max((os.path.getmtime(p) for p in paths), default=0.0)


def files_under(d, content_only=False):
    for base, _dirs, names in os.walk(d):
        for n in names:
            p = os.path.join(base, n)
            if content_only and n.lower().endswith(ARCHIVES):
                skipped.append(os.path.relpath(p, ROOT))
                continue
            yield p


def place(src, dest, origin):
    """Copy src to dest; an existing identical file is fine, a different one is an error."""
    if os.path.exists(dest):
        with open(src, 'rb') as a, open(dest, 'rb') as b:
            same = a.read() == b.read()
        if not same:
            raise SystemExit('conflict: %s differs from the copy already placed at %s (from %s)'
                             % (src, os.path.relpath(dest, OUT), origin.get(dest)))
        return
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    shutil.copy2(src, dest)
    origin[dest] = os.path.relpath(src, ROOT)


def reset_output():
    """Delete what the previous run made (the files BUILD.txt lists, plus BUILD.txt and README.md),
    then prune empty folders. Other files stay. The folder itself stays too: Windows can't remove
    a folder that is open in Explorer or is some process's working directory."""
    os.makedirs(OUT, exist_ok=True)
    build = os.path.join(OUT, 'BUILD.txt')
    if not os.path.exists(build):
        if os.listdir(OUT):
            raise SystemExit('%s has files but no BUILD.txt from this script; not touching it.' % OUT)
        return
    with open(build, encoding='utf-8') as f:
        lines = f.read().splitlines()
    if not lines or not lines[0].startswith(MARKER):
        raise SystemExit('%s/BUILD.txt was not written by this script; not touching the folder.' % OUT)
    ours = ['BUILD.txt', 'README.md']
    in_files = False
    for line in lines:
        if line.startswith('Files (size, source):'):
            in_files = True
        elif in_files and MANIFEST_LINE.match(line):
            ours.append(MANIFEST_LINE.match(line).group(1))
    for rel in ours:
        p = os.path.join(OUT, rel)
        if os.path.isfile(p):
            os.remove(p)
    for base, dirs, files in os.walk(OUT, topdown=False):
        if base != OUT and not os.listdir(base):
            os.rmdir(base)


def foreign_files(origin):
    """Files in the output folder that this run did not write."""
    made = {os.path.normcase(p) for p in origin} | {os.path.normcase(os.path.join(OUT, n)) for n in ('BUILD.txt', 'README.md')}
    return sorted(os.path.relpath(p, OUT) for p in files_under(OUT) if os.path.normcase(p) not in made)


def find_dll():
    for mode in BUILD_MODES:
        dll = os.path.join(ROOT, 'build', 'windows', 'x64', mode, DLL_NAME + '.dll')
        if os.path.exists(dll):
            if mode != BUILD_MODES[0]:
                warnings.append('using the %s DLL build, not %s' % (mode, BUILD_MODES[0]))
            return dll
    raise SystemExit('no %s.dll under build/windows/x64/{%s}; build it with xmake first'
                     % (DLL_NAME, ','.join(BUILD_MODES)))


def add_dll_route(origin):
    dll = find_dll()
    sources = [p for d in ('src', 'include') for p in files_under(os.path.join(ROOT, d))]
    if newest(sources) > os.path.getmtime(dll):
        warnings.append('%s is older than the newest file in src/ or include/: rebuild with xmake'
                        % os.path.relpath(dll, ROOT))
    plugins = os.path.join(OUT, 'SKSE', 'Plugins')
    place(dll, os.path.join(plugins, DLL_NAME + '.dll'), origin)
    pdb = os.path.splitext(dll)[0] + '.pdb'
    if os.path.exists(pdb):  # lets crash loggers name functions
        place(pdb, os.path.join(plugins, DLL_NAME + '.pdb'), origin)
    dist = os.path.join(ROOT, 'dist')
    for p in files_under(dist, content_only=True):
        place(p, os.path.join(OUT, os.path.relpath(p, dist)), origin)
    return dll


def add_papyrus_fallback(origin):
    for mod in PAPYRUS_MODS:
        base = os.path.join(ROOT, 'mods', mod)
        for psc in glob.glob(os.path.join(base, 'Scripts', 'Source', '*.psc')):
            pex = os.path.join(base, 'Scripts', os.path.splitext(os.path.basename(psc))[0] + '.pex')
            if not os.path.exists(pex) or os.path.getmtime(pex) < os.path.getmtime(psc):
                warnings.append('%s is missing or older than its source: run tools/compile_papyrus.py'
                                % os.path.relpath(pex, ROOT))
        for p in files_under(base, content_only=True):
            rel = os.path.relpath(p, base)
            if rel.lower() == 'readme.md':
                rel = 'README - %s.md' % mod
            place(p, os.path.join(FALLBACK, rel), origin)


def write_zip(mod_dir):
    """mods/<mod>.zip with the mod's content at the root. Archives inside the folder are left out."""
    name = os.path.basename(mod_dir)
    dest = os.path.join(ROOT, 'mods', name + '.zip')
    tmp = dest + '.tmp'
    count = 0
    with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(files_under(mod_dir), key=str.lower):
            if p.lower().endswith(ARCHIVES):
                continue
            z.write(p, os.path.relpath(p, mod_dir).replace(os.sep, '/'))
            count += 1
    os.replace(tmp, dest)
    return dest, count


def git_head():
    try:
        head = subprocess.run(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD'],
                              capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(['git', '-C', ROOT, 'status', '--porcelain', '--', 'mods', 'tools'],
                               capture_output=True, text=True).stdout
        dirty = [l for l in dirty.splitlines()
                 if 'mods/OSED Reborn/' not in l and not l.rstrip('"').lower().endswith(ARCHIVES)]
        return head + (' (+ uncommitted changes in mods/ or tools/)' if dirty else '')
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'


README = """# OSED Reborn

OStim Expression Director (OSED) and its Body, Living Skin and Lip-Sync add-ons, rebuilt.
This folder is generated by `tools/assemble_mod.py`; `BUILD.txt` records what went into it.

## What is active

The SKSE plugin, `SKSE/Plugins/OSEDReborn.dll`. It has no plugin (.esp), no Papyrus scripts
and no MCM. Settings are in the SKSE Menu Framework (section "OSED Reborn") and in
`SKSE/Plugins/OSEDReborn.ini`; softbody morph and body-blush tables are in
`SKSE/Plugins/OSEDReborn/morphs.json`.

Changes from the originals that you'll notice: the Living Skin sweat layer is gone (a face
overlay never lined up with the body), and Softbody Arousal no longer drops to zero after an
orgasm; it holds, then eases back.

`optional/Papyrus Fallback/` holds the fixed Papyrus versions of the four original mods. The
game never loads anything from an `optional` folder, so it is inert where it is.

## Before enabling

Disable the original **Ostim Expression Director (OSED)**, **OSED Body**, **OSED Living Skin**,
**OSED Enhanced Moan LipSync** and **Softbody Arousal** in MO2. This mod replaces all of them.
Start a new save for testing.

Install only this mod. The separate **OSED Reborn Core / Body / Living Skin / Lip-Sync** mods
from the same project are the Papyrus fallback below; installing them next to this one runs the
Papyrus engine for faces, body, skin and lip-sync instead of the DLL.

If one is left on by mistake, the DLL turns its own matching module off for that session instead
of fighting it, logs why, and shows one notification ("old mod(s) still active"); the Status page
lists them. Only the matching module stands down: with the old Core plugin active, for example,
the DLL still tracks scenes and runs body, skin, lip-sync and arousal, and only stops painting faces.

## Requirements

- DLL route: SKSE64, Address Library for SKSE Plugins, OStim Standalone, SKSE Menu Framework,
  RaceMenu (skin overlays), and Spell Perk Item Distributor (reads `OSED_Personality_DISTR.ini`).
- Papyrus fallback: OStim Standalone, SkyUI, PapyrusUtil SE, Mfg Fix NG, RaceMenu, SPID.

## Switching to the Papyrus fallback

1. Move everything inside `optional/Papyrus Fallback/` up to this folder's root. Overwriting the
   facial expression files and the SPID ini is fine: they are identical.
2. Enable the four `.esp` files in MO2's plugin list, and start a new save.
3. The DLL sees the fallback plugins (`OSED Reborn Core.esp`, `OSED Reborn Body.esp`,
   `OSED Reborn Living Skin.esp`, `OSED Reborn Lip-Sync.esp`) and switches its Faces, Body,
   Living Skin and Lip-Sync modules off by itself. For a
   pure Papyrus setup, also move `SKSE/Plugins/OSEDReborn.dll` and `.pdb` into `optional/`.

The fallback's own READMEs are `README - <mod>.md`. Lip-Sync's fallback also needs the bake in
`BakeToolkit/` (the DLL's lip-sync does not).
"""


def main():
    reset_output()
    origin = {}
    dll = add_dll_route(origin)
    add_papyrus_fallback(origin)
    with open(os.path.join(OUT, 'README.md'), 'w', encoding='utf-8') as f:
        f.write(README)

    lines = [MARKER + ' on %s' % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
             'Project commit: %s' % git_head(),
             'DLL: %s (built %s)' % (os.path.relpath(dll, ROOT),
                                     datetime.datetime.fromtimestamp(os.path.getmtime(dll)).strftime('%Y-%m-%d %H:%M')),
             '']
    lines += ['WARNING: ' + w for w in warnings]
    kept = foreign_files(origin)
    lines += ['Kept (not made by this script): ' + k for k in kept]
    lines += ['Skipped archive: ' + s for s in skipped]
    lines += ['', 'Files (size, source):']
    for dest in sorted(origin, key=lambda d: os.path.relpath(d, OUT).lower()):
        lines.append('  %-72s %9d  %s' % (os.path.relpath(dest, OUT), os.path.getsize(dest), origin[dest]))
    with open(os.path.join(OUT, 'BUILD.txt'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

    print('Wrote %s: %d files' % (os.path.relpath(OUT, ROOT), len(origin) + 2))
    for k in kept:
        print('kept (not ours): ' + k)
    for s in skipped:
        print('skipped archive: ' + s)
    for mod_dir in [OUT] + [os.path.join(ROOT, 'mods', m) for m in PAPYRUS_MODS]:
        dest, count = write_zip(mod_dir)
        print('zip: %-40s %3d files %9d bytes' % (os.path.relpath(dest, ROOT), count, os.path.getsize(dest)))
    for w in warnings:
        print('WARNING: ' + w)
    return 0


if __name__ == '__main__':
    sys.exit(main())
